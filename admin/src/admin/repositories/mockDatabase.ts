  public subscribe(listener: () => void): () => void {
    this.listeners.add(listener);
    return () => this.listeners.delete(listener);
  }

  public notify(): void {
    this.listeners.forEach((fn) => fn());
  }

  public recordAuditEvent(
    action: string,
    module: AuditLogEvent['module'],
    resourceType: string,
    resourceId: string,
    resourceTitle: string,
    previousValue?: Record<string, any>,
    newValue?: Record<string, any>,
    status: 'success' | 'failure' | 'warning' = 'success'
  ): AuditLogEvent {
    const event: AuditLogEvent = {
      id: `aud-${Date.now().toString(36)}`,
      timestamp: new Date().toISOString(),
      actorId: 'usr-admin-current',
      actorName: this.currentAdminName,
      actorRole: this.currentAdminRole,
      action,
      module,
      resourceType,
      resourceId,
      resourceTitle,
      previousValue,
      newValue,
      status,
      correlationId: `req-${Math.random().toString(36).substring(2, 9)}`,
      ipAddress: '178.89.155.42',
    };
    this.auditLogs.unshift(event);
    this.notify();
    return event;
  }
